"""一次性生成港股名称离线缓存 hk_stock_cache.json（与 stock_cache.json 同级）。

优先用 港股通列表（stock_hk_famous_spot_em，覆盖最全）；
若网络不可用（如被拦截），回退到 AH 两地上市列表（stock_zh_ah_name，~220 只）。
生成的文件供搜索自动补全、港股财报名称解析使用。运行时零网络依赖。

用法：
    python build_hk_cache.py
"""
import os
import json
import akshare as ak

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'hk_stock_cache.json')


def _collect():
    # 0) 内置主流港股兜底（即便网络全不可达也能搜索/解析这些常见标的）
    out = dict(CURATED)
    # 1) 港股通列表（最全，覆盖最广）
    try:
        df = ak.stock_hk_famous_spot_em()
        for _, row in df.iterrows():
            code = str(row.get('代码', row.get('code', ''))).strip()
            name = str(row.get('名称', row.get('name', ''))).strip()
            if code:
                out[code.zfill(5)] = name
        print(f'港股通列表：{len(out)} 只')
    except Exception as e:
        print('港股通列表获取失败（可能网络被拦截）：', repr(e)[:120])
    # 2) 回退/补充：AH 两地上市
    try:
        df = ak.stock_zh_ah_name()
        for _, row in df.iterrows():
            code = str(row.get('代码', row.get('code', ''))).strip()
            name = str(row.get('名称', row.get('name', ''))).strip()
            if code and code.zfill(5) not in out:
                out[code.zfill(5)] = name
        print(f'AH 补充后：{len(out)} 只')
    except Exception as e:
        print('AH 列表获取失败：', repr(e)[:120])
    return out


